require "json"
require "open3"
require_relative "../../mrblib/base"

module ActiveD1
  class Generator
    # Query Wrangler's public local D1 interface, including generated columns.
    SCHEMA_SQL = <<~SQL
      SELECT t.name AS table_name, c.name, c.type, c."notnull" AS required,
             c.dflt_value, c.pk, c.hidden
      FROM pragma_table_list() AS t JOIN pragma_table_xinfo(t.name) AS c
      WHERE t.schema = 'main' AND t.type = 'table'
        AND lower(t.name) NOT GLOB 'sqlite_*' AND lower(t.name) NOT GLOB '_cf_*'
        AND t.name <> 'd1_migrations'
      ORDER BY t.name, c.cid
    SQL

    def self.read_local(database, config: nil, persist_to: nil)
      args = ["npx", "--no-install", "wrangler", "d1", "execute", database, "--local", "--json", "--command", SCHEMA_SQL]
      args.concat(["--config", config]) if config
      args.concat(["--persist-to", persist_to]) if persist_to
      stdout, stderr, status = Open3.capture3(*args)
      raise "Wrangler D1 failed: #{stderr} #{stdout}" unless status.success?
      JSON.parse(stdout).fetch(0).fetch("results")
    end

    # Only emit Ruby method syntax for ordinary column names. Every column
    # remains accessible through record[name], including collisions like "save".
    RESERVED = (Base.instance_methods + Base.private_instance_methods).map(&:to_s)
    def self.render(rows)
      lines = ["# Generated by actived1. Edit the migration and regenerate.", "module ActiveD1", "  module Generated"]
      rows.group_by { |row| row.fetch("table_name") }.each do |name, columns|
        keys = columns.select { |column| column.fetch("pk") > 0 }
        unless keys.size == 1
          warn "Skipping #{name.inspect}: ActiveD1 requires a single primary key"
          next
        end
        key = keys.first.fetch("name")
        suffix = name.b.bytes.map { |byte| byte.chr.match?(/[A-Za-z0-9]/) ? byte.chr : "_%02x" % byte }.join
        mod = "Columns_#{suffix}"
        lines << "    module #{mod}"
        columns.each do |column|
          field = column.fetch("name")
          next unless field.match?(/\A[a-z_][a-zA-Z0-9_]*\z/)
          next if field.match?(/\A_[1-9]\z/) || RESERVED.include?(field)
          lines.concat(["      def #{field}", "        self[#{field.dump}]", "      end"])
          next unless column.fetch("hidden").zero?
          lines.concat(["      def #{field}=(value)", "        self[#{field.dump}] = value", "      end"])
        end
        lines << "    end" << ""
        lines << "    Schema.register(#{name.dump}, #{key.dump}, {"
        columns.each do |column|
          type = column.fetch("type").to_s
          not_null = !column.fetch("required").zero?
          default = column.fetch("dflt_value")
          writable = column.fetch("hidden").zero?
          lines << "      #{column.fetch('name').dump} => { type: #{type.dump}, not_null: #{not_null}, default_sql: #{default.inspect}, writable: #{writable} },"
        end
        lines << "    }, #{mod})" << ""
      end
      (lines + ["  end", "end", ""]).join("\n")
    end
  end
end
